#!/usr/bin/env python3
"""Vendor Shared Contracts and Libraries into Individual Skills.

Usage:
  python tools/vendor_shared.py           # Update vendored files in all skills
  python tools/vendor_shared.py --check   # Verify vendored files match _shared/ source (CI Gate)
"""

import hashlib
import os
import shutil
import sys
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent
SHARED_DIR = ROOT_DIR / "_shared"
CONTRACT_SRC = SHARED_DIR / "contracts" / "canonical-invariants-contract.md"
LIB_SRC = SHARED_DIR / "lib" / "hermes_io.py"

TARGET_SKILLS = [
    "viethoa",
    "cron-tuning",
    "fonttv",
    "bientaptay",
    "buildpatch",
]


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()


def generate_header(src_name: str, src_sha256: str, comment_prefix: str = "#") -> str:
    return (
        f"{comment_prefix} =====================================================================\n"
        f"{comment_prefix} AUTOGENERATED VENDOR COPY - DO NOT EDIT DIRECTLY\n"
        f"{comment_prefix} Source: _shared/{src_name}\n"
        f"{comment_prefix} Source SHA256: {src_sha256}\n"
        f"{comment_prefix} Managed by: tools/vendor_shared.py\n"
        f"{comment_prefix} =====================================================================\n\n"
    )


def vendor_all(check_mode: bool = False) -> int:
    if not CONTRACT_SRC.exists() or not LIB_SRC.exists():
        print(f"[ERROR] Source files missing in {SHARED_DIR}", file=sys.stderr)
        return 1

    contract_sha = sha256_file(CONTRACT_SRC)
    lib_sha = sha256_file(LIB_SRC)
    
    contract_content = CONTRACT_SRC.read_text(encoding="utf-8")
    lib_content = LIB_SRC.read_text(encoding="utf-8")

    contract_vendored_payload = (
        f"<!---\n"
        f"AUTOGENERATED VENDOR COPY - DO NOT EDIT DIRECTLY\n"
        f"Source: _shared/contracts/canonical-invariants-contract.md\n"
        f"Source SHA256: {contract_sha}\n"
        f"Managed by: tools/vendor_shared.py\n"
        f"--->\n\n"
        + contract_content
    )

    lib_vendored_payload = (
        generate_header("lib/hermes_io.py", lib_sha, comment_prefix="#")
        + lib_content
    )

    drift_count = 0

    for skill in TARGET_SKILLS:
        skill_dir = ROOT_DIR / "skills" / skill
        if not skill_dir.exists():
            continue

        target_contract = skill_dir / "references" / "contracts" / "canonical-invariants-contract.md"
        target_lib = skill_dir / "scripts" / "_vendor" / "hermes_io.py"

        # Check / Write Contract
        if check_mode:
            if not target_contract.exists():
                print(f"[CHECK FAILED] Missing vendored contract: {target_contract}", file=sys.stderr)
                drift_count += 1
            else:
                existing = target_contract.read_text(encoding="utf-8")
                if existing != contract_vendored_payload:
                    print(f"[CHECK FAILED] Vendored contract drift in {skill}", file=sys.stderr)
                    drift_count += 1

            if not target_lib.exists():
                print(f"[CHECK FAILED] Missing vendored lib: {target_lib}", file=sys.stderr)
                drift_count += 1
            else:
                existing = target_lib.read_text(encoding="utf-8")
                if existing != lib_vendored_payload:
                    print(f"[CHECK FAILED] Vendored lib drift in {skill}", file=sys.stderr)
                    drift_count += 1
        else:
            target_contract.parent.mkdir(parents=True, exist_ok=True)
            target_lib.parent.mkdir(parents=True, exist_ok=True)

            target_contract.write_text(contract_vendored_payload, encoding="utf-8")
            target_lib.write_text(lib_vendored_payload, encoding="utf-8")
            print(f"[VENDORED] -> {skill}: contract & hermes_io.py updated.")

    if check_mode:
        if drift_count == 0:
            print("[CHECK PASSED] All vendored artifacts are in sync with _shared/ source.")
            return 0
        else:
            print(f"[CHECK FAILED] Found {drift_count} drifted or missing vendored files.", file=sys.stderr)
            return 2

    print("[SUCCESS] Vendoring complete across all skills.")
    return 0


if __name__ == "__main__":
    check = "--check" in sys.argv
    sys.exit(vendor_all(check_mode=check))
